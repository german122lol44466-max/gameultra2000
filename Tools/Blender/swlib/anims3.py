"""
Строевые стойки и походки для «Командира клонов» (поверх набора винтовки из anims2):

  Attention   — «Смирно»: пятки вместе, корпус прямо, винтовка стволом вниз вдоль правой ноги
  AtEase      — «Вольно»: ноги на ширине плеч, винтовка опущена поперёк корпуса, осматривается
  PortArms    — «На грудь»: винтовка по диагонали перед грудью (патруль, строй)
  March       — строевой шаг с винтовкой на груди (высокий подъём ноги, 1.35 м/с)
  Patrol      — шаг с опущенной винтовкой, медленный, голова крутится (1.1 м/с)
  CrouchWalk  — гусиный шаг на полусогнутых с оружием у плеча (0.9 м/с)
  CrouchIdle  — присел, оружие опущено
  Prone       — лёжа, оружие наготове;  ProneAim — лёжа, прицеливание
  Point       — команда рукой: левая вытянута вперёд (приказ «вперёд»)
  Halt        — команда «стой»: левая ладонь поднята
  Salute      — отдание чести левой рукой у шлема (оружие в правой стволом вниз)

Соглашения пространства персонажа как в anims2: +X — влево, -Y — вперёд, Z — вверх, рост 1.83.
"""

import math

from .anims2 import ANKLE, FIST, FX, OPEN, K, cycle, gait, neutral, over, rifle_poses

FLAT = (0.08, None, 0.0, 0.1)        # прямая ладонь (команды, «смирно»)
POINT = (0.9, 0.0, 0.0, 0.8)         # указательный вытянут, остальные сжаты


def formation_clips():
    b, low, aim, crouch, crouch_low = rifle_poses()
    C = {}
    free_l = dict(lgrip=0.0, lh=(0.235, -0.005, 0.88), lhf=(0.0, -0.05, -1.0), lht=(0.0, -1.0, 0.0), lf=FLAT)

    # ---------------------------------------------------------------- Смирно
    att = over(b, **free_l,
               w=(-0.255, -0.035, 0.80, 0.0, -88.0, 0.0), wup=(0.0, -1.0, 0.0),
               fl=(0.075, 0.0, ANKLE, 9.0, 0.0), fr=(-0.075, 0.0, ANKLE, -9.0, 0.0),
               hips=(0.0, 0.0, 0.0), chest=(-3.0, 0.0, 0.0), spine=(-1.0, 0.0, 0.0), head=(-2.0, 0.0, 0.0),
               elbl=(0.6, 0.6, 1.0), elbr=(-0.6, 0.6, 1.0), kl=(0.1, -0.8, 0.55), kr=(-0.1, -0.8, 0.55))
    C["Attention"] = K([(0, att), (45, over(att, chest=(-3.6, 0, 0), hips=(0, 0, 0.003))), (90, att)], 90, loop=True)

    # ---------------------------------------------------------------- Вольно
    ease = over(b, w=(-0.07, -0.2, 0.96, 62.0, -48.0, -25.0), lgrip=1.0,
                fl=(0.17, 0.0, ANKLE, 12.0, 0.0), fr=(-0.17, 0.02, ANKLE, -14.0, 0.0),
                hips=(0.015, 0.0, -0.01), hipr=(0.0, 2.0, 0.0), spine=(2.0, 0.0, 0.0), chest=(1.0, 0.0, 0.0))
    C["AtEase"] = K([(0, ease), (40, over(ease, head=(-3.0, 18.0, 0), chest=(2.0, 0, 0))),
                     (80, over(ease, head=(-1.0, -15.0, 0), hips=(0.018, 0, -0.012))), (120, ease)], 120, loop=True)

    # ---------------------------------------------------------------- На грудь (порт)
    port = over(b, w=(-0.06, -0.22, 1.14, 58.0, 38.0, -70.0), wup=(0.0, -1.0, 0.4), lgrip=1.0,
                spine=(1.0, 0.0, 0.0), chest=(-1.0, 0.0, 0.0), head=(-2.0, 0.0, 0.0),
                fl=(0.1, 0.0, ANKLE, 8.0, 0.0), fr=(-0.1, 0.0, ANKLE, -8.0, 0.0), elbr=(-0.55, 0.2, 1.0), elbl=(0.4, 0.2, 0.9))
    C["PortArms"] = K([(0, port), (45, over(port, chest=(-1.6, 0, 0))), (90, port)], 90, loop=True)

    def march(t):
        g = gait(t, 0.78, 0.13, duty=0.58, bob=0.016, sway=2.0)
        s = math.sin(2 * math.pi * t)
        p = over(port, **g)
        x, y, z, yw, pt, rl = port["w"]
        p["w"] = (x, y, z + g["hips"][2] * 0.9, yw + 1.0 * s, pt, rl)
        p["chest"] = (-1.5, 2.0 * s, 0.0)
        p["kl"] = (0.15, -1.0, 0.7)
        p["kr"] = (-0.15, -1.0, 0.7)
        return p
    C["March"] = cycle(34, march)

    def patrol(t):
        g = gait(t, 0.66, 0.05, duty=0.62, bob=0.014, sway=3.0)
        s = math.sin(2 * math.pi * t)
        p = over(low, **g)
        x, y, z, yw, pt, rl = low["w"]
        p["w"] = (x, y, z + g["hips"][2] * 0.8, yw + 1.5 * s, pt, rl)
        p["head"] = (-3.0, 0.0, 0.0)
        return p
    C["Patrol"] = cycle(36, patrol)

    def cwalk(t):
        g = gait(t, 0.55, 0.07, duty=0.62, bob=0.015, sway=2.0, crouch=0.3, width=0.15)
        p = over(crouch, **g)
        x, y, z, yw, pt, rl = crouch["w"]
        p["w"] = (x, y, z - 0.02 + (g["hips"][2] + 0.3) * 0.8, yw, pt, rl)
        p["hipr"] = (6.0, 0.0, crouch["hipr"][2] * 0.5 + g["hipr"][2])
        p["spine"] = (8.0, 4.0, 0.0)
        p["neck"] = (6.0, 0.0, -4.0)
        p["head"] = (10.0, 0.0, -6.0)
        p["kl"] = (0.3, -1.0, 0.5)
        p["kr"] = (-0.3, -1.0, 0.5)
        return p
    C["CrouchWalk"] = cycle(36, cwalk)
    C["CrouchIdle"] = K([(0, crouch_low), (40, over(crouch_low, head=(-2.0, 15.0, 0))), (80, over(crouch_low, head=(-2.0, -12.0, 0))),
                         (120, crouch_low)], 120, loop=True)

    # ---------------------------------------------------------------- Лёжа
    prone = over(b, hips=(0.0, 0.08, -0.86), hipr=(86.0, 0.0, 0.0), spine=(-10.0, 0.0, 0.0), chest=(-14.0, 0.0, 0.0),
                 neck=(-18.0, 0.0, 0.0), head=(-26.0, 0.0, 0.0),
                 w=(-0.09, -0.78, 0.2, 2.0, 2.0, 0.0), lgrip=1.0,
                 fl=(0.2, 1.02, 0.07, 8.0, -80.0), fr=(-0.2, 1.02, 0.07, -8.0, -80.0),
                 kl=(0.3, 0.6, -0.8), kr=(-0.3, 0.6, -0.8),
                 elbl=(0.4, -0.3, -0.2), elbr=(-0.4, -0.3, -0.2))
    C["Prone"] = K([(0, over(prone, w=(-0.12, -0.72, 0.16, 15.0, -8.0, -10.0))), (60, over(prone, w=(-0.12, -0.72, 0.162, 15.0, -8.0, -10.0),
                    head=(-24.0, 8.0, 0))), (120, over(prone, w=(-0.12, -0.72, 0.16, 15.0, -8.0, -10.0)))], 120, loop=True)
    C["ProneAim"] = K([(0, prone), (30, over(prone, w=(-0.09, -0.78, 0.203, 2.2, 2.2, 0.0))), (60, prone)], 60, loop=True)
    kick = over(prone, w=(-0.09, -0.76, 0.21, 2.0, 6.0, 1.0), rf=(1.0, 0.9, 0, 0.7))
    C["ProneFire"] = K([(0, prone), (2, kick), (9, prone)], 9)
    # переходы
    C["GoProne"] = K([(0, low), (8, over(crouch_low, hips=(0.0, -0.1, -0.5))), (16, over(prone, hips=(0.0, -0.05, -0.7), hipr=(55.0, 0, 0))),
                      (26, prone)], 26)
    C["StandUp"] = K([(0, prone), (10, over(prone, hips=(0.0, -0.05, -0.7), hipr=(55.0, 0, 0))), (18, over(crouch_low, hips=(0.0, -0.1, -0.5))),
                      (28, low)], 28)

    # ---------------------------------------------------------------- Жесты
    point_out = over(low, lgrip=0.0, lh=(0.16, -0.6, 1.42), lhf=(-0.1, -1.0, 0.12), lht=(0.0, 0.0, 1.0), lf=POINT,
                     elbl=(0.6, 0.0, 1.2), chest=(2.0, -6.0, 0.0), head=(-4.0, -4.0, 0.0),
                     w=(-0.16, -0.18, 1.02, 10.0, -45.0, -15.0))
    C["Point"] = K([(0, low), (6, over(point_out, lh=(0.2, -0.35, 1.3))), (11, point_out), (24, point_out), (34, low)], 34)
    halt = over(point_out, lh=(0.24, -0.25, 1.62), lhf=(0.0, -0.1, 1.0), lht=(-1.0, 0.0, 0.0), lf=FLAT, elbl=(0.7, 0.1, 1.2))
    C["Halt"] = K([(0, low), (6, over(halt, lh=(0.24, -0.25, 1.4))), (10, halt), (24, halt), (34, low)], 34)
    sal = over(att, lh=(0.07, -0.12, 1.69), lhf=(-0.75, -0.25, 0.3), lht=(0.0, -0.3, 1.0), lf=FLAT, elbl=(0.8, -0.3, 1.5))
    C["Salute"] = K([(0, att), (7, over(sal, lh=(0.16, -0.18, 1.45))), (12, sal), (36, sal), (46, att)], 46)
    return C


FORMATION_LOOPING = {"Attention", "AtEase", "PortArms", "March", "Patrol", "CrouchWalk", "CrouchIdle", "Prone", "ProneAim"}
